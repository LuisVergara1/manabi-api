-- Administrative identities only; no passwords/seeds or educational changes.
CREATE TABLE admin_user (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(64) COLLATE "C" NOT NULL UNIQUE CHECK(username ~ '^[A-Za-z0-9][A-Za-z0-9._-]{2,63}$'),
 password_hash VARCHAR(100) NOT NULL CHECK(password_hash ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$'),
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 auth_revision BIGINT NOT NULL DEFAULT 0 CHECK(auth_revision>=0),
 created_at TIMESTAMPTZ NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE admin_user_role (
 user_id BIGINT NOT NULL REFERENCES admin_user(id) ON DELETE CASCADE,
 role VARCHAR(16) NOT NULL CHECK(role IN ('ADMIN','EDITOR','REVIEWER','PUBLISHER')),
 PRIMARY KEY(user_id,role)
);
CREATE TABLE admin_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor VARCHAR(64) NOT NULL,
 action VARCHAR(48) NOT NULL,
 target VARCHAR(256) NOT NULL,
 outcome VARCHAR(16) NOT NULL CHECK(outcome IN ('SUCCESS','DENIED','FAILURE')),
 occurred_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX ix_admin_audit_time ON admin_audit(occurred_at,id);
