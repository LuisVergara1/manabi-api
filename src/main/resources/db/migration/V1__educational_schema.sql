-- Clean Manabi development schema. Empty database required. Flyway runs this transactionally.
CREATE TABLE kana (
    public_id VARCHAR(128) COLLATE "C" NOT NULL UNIQUE,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kana_character VARCHAR(32) COLLATE "C" NOT NULL,
    romaji VARCHAR(64) NOT NULL,
    type VARCHAR(16) NOT NULL,
    group_type VARCHAR(16) NOT NULL,
    display_order BIGINT NOT NULL CHECK (display_order BETWEEN 0 AND 9007199254740991),
    version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE kanji (
    public_id VARCHAR(128) COLLATE "C" NOT NULL UNIQUE,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kanji_character VARCHAR(16) COLLATE "C" NOT NULL,
    meaning TEXT NOT NULL,
    stroke_count INTEGER NOT NULL,
    jlpt_level VARCHAR(2) NOT NULL,
    display_order BIGINT NOT NULL CHECK (display_order BETWEEN 0 AND 9007199254740991),
    radical_character VARCHAR(16),
    radical_name VARCHAR(120),
    version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE kanji_reading (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kanji_id BIGINT NOT NULL,
    reading VARCHAR(128) COLLATE "C" NOT NULL,
    reading_type VARCHAR(16) NOT NULL,
    romaji VARCHAR(256),
    is_primary BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE kanji_example (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kanji_id BIGINT NOT NULL,
    japanese VARCHAR(512) NOT NULL,
    reading VARCHAR(512) NOT NULL,
    meaning TEXT NOT NULL,
    display_order BIGINT NOT NULL CHECK (display_order BETWEEN 0 AND 9007199254740991)
);
CREATE TABLE vocabulary (
    public_id VARCHAR(128) COLLATE "C" NOT NULL UNIQUE,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    japanese VARCHAR(256) NOT NULL,
    kana VARCHAR(256) NOT NULL,
    romaji VARCHAR(512) NOT NULL,
    meaning TEXT NOT NULL,
    display_order BIGINT NOT NULL CHECK (display_order BETWEEN 0 AND 9007199254740991),
    version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE vocabulary_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) COLLATE "C" NOT NULL,
    name VARCHAR(120) NOT NULL,
    symbol VARCHAR(16),
    display_order BIGINT NOT NULL CHECK (display_order BETWEEN 0 AND 9007199254740991),
    show_in_catalog BOOLEAN NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE vocabulary_category_membership (
    vocabulary_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    PRIMARY KEY (vocabulary_id, category_id)
);

