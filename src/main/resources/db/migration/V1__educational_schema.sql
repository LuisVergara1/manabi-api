CREATE TABLE phrase_category (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 public_id VARCHAR(128) COLLATE "C" NOT NULL UNIQUE CHECK(public_id ~ '^[A-Za-z0-9_-]+$'),
 name TEXT NOT NULL CHECK(btrim(name) <> ''),
 description TEXT NOT NULL CHECK(btrim(description) <> ''),
 display_order BIGINT NOT NULL CHECK(display_order BETWEEN 0 AND 9007199254740991),
 enabled BOOLEAN NOT NULL,
 version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE particle (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 public_id VARCHAR(128) COLLATE "C" NOT NULL UNIQUE CHECK(public_id ~ '^[A-Za-z0-9_-]+$'),
 japanese TEXT NOT NULL CHECK(btrim(japanese) <> ''),
 title TEXT NOT NULL CHECK(btrim(title) <> ''),
 explanation TEXT NOT NULL CHECK(btrim(explanation) <> ''),
 version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE phrase (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 public_id VARCHAR(128) COLLATE "C" NOT NULL UNIQUE CHECK(public_id ~ '^[A-Za-z0-9_-]+$'),
 kind VARCHAR(16) NOT NULL CHECK(kind IN ('FIXED','PATTERN')),
 display_order BIGINT NOT NULL CHECK(display_order BETWEEN 0 AND 9007199254740991),
 japanese TEXT NOT NULL CHECK(btrim(japanese) <> ''),
 kana TEXT NOT NULL CHECK(btrim(kana) <> ''),
 romaji TEXT NOT NULL CHECK(btrim(romaji) <> ''),
 meaning TEXT NOT NULL CHECK(btrim(meaning) <> ''),
 icon_type VARCHAR(32) NOT NULL,
 introduction TEXT NOT NULL CHECK(btrim(introduction) <> ''),
 usage_note TEXT CHECK(usage_note IS NULL OR btrim(usage_note) <> ''),
 pattern_formula TEXT,
 pattern_explanation TEXT,
 version BIGINT NOT NULL DEFAULT 0,
 CONSTRAINT ck_phrase_pattern_v5 CHECK(
  (kind='FIXED' AND pattern_formula IS NULL AND pattern_explanation IS NULL) OR
  (kind='PATTERN' AND pattern_formula IS NOT NULL AND btrim(pattern_formula) <> ''
   AND pattern_explanation IS NOT NULL AND btrim(pattern_explanation) <> '')
 )
);
CREATE TABLE phrase_category_membership (
 phrase_id BIGINT NOT NULL REFERENCES phrase(id) ON DELETE CASCADE,
 category_id BIGINT NOT NULL REFERENCES phrase_category(id) ON DELETE RESTRICT,
 PRIMARY KEY(phrase_id,category_id)
);
CREATE INDEX ix_phrase_category_lookup_v5 ON phrase_category_membership(category_id,phrase_id);
CREATE INDEX ix_phrase_editorial_order_v5 ON phrase(display_order,public_id);
CREATE TABLE phrase_example (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 phrase_id BIGINT NOT NULL REFERENCES phrase(id) ON DELETE CASCADE,
 public_id VARCHAR(128) COLLATE "C" NOT NULL UNIQUE,
 display_order BIGINT NOT NULL CHECK(display_order BETWEEN 0 AND 9007199254740991),
 japanese TEXT NOT NULL CHECK(btrim(japanese) <> ''),
 kana TEXT NOT NULL CHECK(btrim(kana) <> ''),
 romaji TEXT NOT NULL CHECK(btrim(romaji) <> ''),
 meaning TEXT NOT NULL CHECK(btrim(meaning) <> ''),
 icon_type VARCHAR(32) NOT NULL,
 situation TEXT CHECK(situation IS NULL OR btrim(situation) <> '')
);
CREATE INDEX ix_phrase_example_order_v5 ON phrase_example(phrase_id,display_order,public_id);
CREATE TABLE phrase_meaning (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 phrase_id BIGINT NOT NULL REFERENCES phrase(id) ON DELETE CASCADE,
 public_id VARCHAR(128) COLLATE "C" NOT NULL,
 position INTEGER NOT NULL CHECK(position >= 0),
 label TEXT NOT NULL CHECK(btrim(label) <> ''), explanation TEXT NOT NULL CHECK(btrim(explanation) <> ''), icon_type VARCHAR(32) NOT NULL,
 UNIQUE(phrase_id,public_id),
 UNIQUE(phrase_id,position) DEFERRABLE INITIALLY DEFERRED
);
CREATE TABLE phrase_slot (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 phrase_id BIGINT NOT NULL REFERENCES phrase(id) ON DELETE CASCADE,
 public_id VARCHAR(128) COLLATE "C" NOT NULL,
 position INTEGER NOT NULL CHECK(position >= 0),
 label TEXT NOT NULL CHECK(btrim(label) <> ''), description TEXT NOT NULL CHECK(btrim(description) <> ''),
 UNIQUE(phrase_id,public_id),
 UNIQUE(phrase_id,position) DEFERRABLE INITIALLY DEFERRED
);
CREATE TABLE phrase_learning_key (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 phrase_id BIGINT NOT NULL REFERENCES phrase(id) ON DELETE CASCADE,
 public_id VARCHAR(128) COLLATE "C" NOT NULL,
 position INTEGER NOT NULL CHECK(position >= 0),
 icon_type VARCHAR(32) NOT NULL,
 particle_id BIGINT REFERENCES particle(id) ON DELETE RESTRICT,
 title TEXT, explanation TEXT,
 example_japanese TEXT, example_kana TEXT, example_romaji TEXT, example_meaning TEXT,
 CONSTRAINT ck_learning_source_v5 CHECK(
  (particle_id IS NOT NULL AND title IS NULL AND explanation IS NULL) OR
  (particle_id IS NULL AND title IS NOT NULL AND btrim(title) <> '' AND explanation IS NOT NULL AND btrim(explanation) <> '')
 ),
 CONSTRAINT ck_learning_aux_v5 CHECK(
  (example_japanese IS NULL AND example_kana IS NULL AND example_romaji IS NULL AND example_meaning IS NULL) OR
  (example_japanese IS NOT NULL AND btrim(example_japanese) <> '' AND example_kana IS NOT NULL AND btrim(example_kana) <> ''
   AND example_romaji IS NOT NULL AND btrim(example_romaji) <> '' AND example_meaning IS NOT NULL AND btrim(example_meaning) <> '')
 ),
 UNIQUE(phrase_id,public_id),
 UNIQUE(phrase_id,position) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX ix_phrase_particle_reference_v5 ON phrase_learning_key(particle_id);
CREATE TABLE phrase_key_point (
 phrase_id BIGINT NOT NULL REFERENCES phrase(id) ON DELETE CASCADE,
 position INTEGER NOT NULL CHECK(position BETWEEN 0 AND 2),
 text TEXT NOT NULL CHECK(btrim(text) <> ''),
 PRIMARY KEY(phrase_id,position)
);
